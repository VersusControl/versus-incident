#!/usr/bin/env bash
# Regenerate examples/kubernetes/k8s-connector-in-cluster-enabled.yaml, the one-file manifest for
# `kubectl apply`, from the Helm chart with the in-cluster Kubernetes connector
# turned on (connectors.kubernetes.enabled=true) and otherwise default values.
#
# The manifest installs into the namespace "versus" and reads the sign-in
# secret from a Secret named "versus-incident" (key gateway_secret) that the
# user creates first, so no secret is committed in the file.
#
# Usage:
#   scripts/render_kubernetes_manifest.sh          rewrite the committed file
#   scripts/render_kubernetes_manifest.sh --check  exit 1 if it is out of date

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CHART_DIR="$ROOT_DIR/helm/versus-incident"
MANIFEST="$ROOT_DIR/examples/kubernetes/k8s-connector-in-cluster-enabled.yaml"
NAMESPACE="versus"
RELEASE="versus-incident"
SIGN_IN_SECRET="versus-incident"

if ! command -v helm >/dev/null 2>&1; then
  echo "helm not found; install Helm 3.x" >&2
  exit 2
fi

if [ -z "$(ls -A "$CHART_DIR/charts" 2>/dev/null)" ]; then
  helm dependency build "$CHART_DIR" >/dev/null
fi

render() {
  local app_version
  app_version="$(sed -n 's/^appVersion: *"\{0,1\}\([^"]*\)"\{0,1\}$/\1/p' "$CHART_DIR/Chart.yaml")"
  cat <<EOF
# Versus Incident v${app_version}: one-file install for an existing cluster, with
# the in-cluster Kubernetes connector enabled and its read-only reader role.
#
# Generated by scripts/render_kubernetes_manifest.sh from the Helm chart with
# connectors.kubernetes.enabled=true and otherwise default values. Do not edit
# by hand; edit the chart and regenerate.
#
# Before applying, create the namespace and the sign-in secret:
#   kubectl create namespace ${NAMESPACE}
#   kubectl -n ${NAMESPACE} create secret generic ${SIGN_IN_SECRET} --from-literal=gateway_secret=\$(openssl rand -hex 32)
---
apiVersion: v1
kind: Namespace
metadata:
  name: ${NAMESPACE}
EOF
  helm template "$RELEASE" "$CHART_DIR" \
    --namespace "$NAMESPACE" \
    --set connectors.kubernetes.enabled=true \
    --set gatewaySecretExistingSecret="$SIGN_IN_SECRET"
}

case "${1:-}" in
  --check)
    if ! diff -u "$MANIFEST" <(render) >&2; then
      echo "examples/kubernetes/k8s-connector-in-cluster-enabled.yaml is out of date; run scripts/render_kubernetes_manifest.sh" >&2
      exit 1
    fi
    echo "examples/kubernetes/k8s-connector-in-cluster-enabled.yaml is up to date"
    ;;
  "")
    mkdir -p "$(dirname "$MANIFEST")"
    render >"$MANIFEST"
    echo "wrote $MANIFEST"
    ;;
  *)
    echo "usage: $0 [--check]" >&2
    exit 2
    ;;
esac
