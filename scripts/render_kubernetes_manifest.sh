#!/usr/bin/env bash
# Regenerate the one-file manifests in examples/kubernetes/ for `kubectl apply`,
# each rendered from the Helm chart with one values file from the same folder:
#
#   k8s-connector-in-cluster-enabled.yaml  values-kubernetes-in-cluster.yaml
#   agent-only.yaml                        values-agent-only.yaml
#   webhook-only.yaml                      values-webhook-only.yaml
#
# Every manifest installs into the namespace "versus" and reads the sign-in
# secret from a Secret named "versus-incident" (key gateway_secret) that the
# user creates first, so no secret is committed in the files. The webhook-only
# manifest also leaves out the chart's own Secret, which would carry the
# channel credentials; the user creates it from the command in its header.
#
# Usage:
#   scripts/render_kubernetes_manifest.sh          rewrite the committed files
#   scripts/render_kubernetes_manifest.sh --check  exit 1 if any is out of date

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CHART_DIR="$ROOT_DIR/helm/versus-incident"
EXAMPLES_DIR="$ROOT_DIR/examples/kubernetes"
NAMESPACE="versus"
RELEASE="versus-incident"
SIGN_IN_SECRET="versus-incident"
CHART_SECRET="${RELEASE}-secrets"

if ! command -v helm >/dev/null 2>&1; then
  echo "helm not found; install Helm 3.x" >&2
  exit 2
fi

APP_VERSION="$(sed -n 's/^appVersion: *"\{0,1\}\([^"]*\)"\{0,1\}$/\1/p' "$CHART_DIR/Chart.yaml")"

# helm_template VALUES_FILE: the chart rendered with one values file. The
# chart pins the image to v<appVersion> for Helm installs; the one-file
# manifests are served from the main branch, so they drop that tag and pull
# the image without a tag instead.
helm_template() {
  helm template "$RELEASE" "$CHART_DIR" \
    --namespace "$NAMESPACE" \
    -f "$EXAMPLES_DIR/$1" \
    --set gatewaySecretExistingSecret="$SIGN_IN_SECRET" |
    sed "s|^\( *image: \"[^\":]*\):v${APP_VERSION}\"\$|\1\"|"
}

# without_chart_secret: drop the chart's Secret document from a rendered
# stream, so the file carries no credential placeholders.
without_chart_secret() {
  awk '
    function flush() { if (doc != "" && doc !~ /# Source: [^\n]*\/templates\/secret\.yaml/) printf "%s", doc; doc = "" }
    /^---$/ { flush(); doc = $0 "\n"; next }
    { doc = doc $0 "\n" }
    END { flush() }
  '
}

namespace_document() {
  cat <<EOF
---
apiVersion: v1
kind: Namespace
metadata:
  name: ${NAMESPACE}
EOF
}

sign_in_secret_steps() {
  cat <<EOF
# Before applying, create the namespace and the sign-in secret:
#   kubectl create namespace ${NAMESPACE} --save-config
#   kubectl -n ${NAMESPACE} create secret generic ${SIGN_IN_SECRET} --from-literal=gateway_secret=\$(openssl rand -hex 32)
EOF
}

render_kubernetes_in_cluster() {
  cat <<EOF
# Versus Incident: one-file install for an existing cluster, with
# the in-cluster Kubernetes connector enabled and its read-only reader role.
#
# Generated by scripts/render_kubernetes_manifest.sh from the Helm chart with
# connectors.kubernetes.enabled=true and otherwise default values. Do not edit
# by hand; edit the chart and regenerate.
#
EOF
  sign_in_secret_steps
  namespace_document
  helm_template values-kubernetes-in-cluster.yaml
}

render_agent_only() {
  cat <<EOF
# Versus Incident: one-file install of the log agent only. The
# agent reads one Loki source (http://loki.monitoring:3100) in training mode;
# the Kubernetes connector and the alert channels are off.
#
# Generated by scripts/render_kubernetes_manifest.sh from the Helm chart with
# examples/kubernetes/values-agent-only.yaml. Do not edit by hand; edit the
# values file and regenerate. To point it at your Loki, edit the
# agent_sources.yaml key of the ConfigMap below, then restart the Deployment.
#
# Training learns only the lines that match the learning pattern (plus a few
# named rules: out of memory, panics, HTTP 5xx). The default pattern learns
# lines containing "error"; info and warn lines are skipped. To learn every
# line, set agent.regex.default_pattern: ".*" in the config.yaml key of the
# ConfigMap below.
#
# The Loki query only selects streams: the service name of a line is read from
# the line itself (service=checkout, app=checkout), not from the stream label.
#
EOF
  sign_in_secret_steps
  namespace_document
  helm_template values-agent-only.yaml
}

render_webhook_only() {
  cat <<EOF
# Versus Incident: one-file install of the alert router only.
# Alerts POSTed to http://${RELEASE}.${NAMESPACE}:3000/api/incidents go to Slack
# and Microsoft Teams; the agent, the Kubernetes connector and on-call are off.
#
# Generated by scripts/render_kubernetes_manifest.sh from the Helm chart with
# examples/kubernetes/values-webhook-only.yaml. Do not edit by hand; edit the
# values file and regenerate.
#
EOF
  sign_in_secret_steps
  cat <<EOF
# and the channel secret, which this file does not contain:
#   kubectl -n ${NAMESPACE} create secret generic ${CHART_SECRET} \\
#     --from-literal=slack_token=\$SLACK_BOT_TOKEN \\
#     --from-literal=slack_channel_id=\$SLACK_CHANNEL_ID \\
#     --from-literal=msteams_power_automate_url=\$TEAMS_POWER_AUTOMATE_URL
EOF
  namespace_document
  helm_template values-webhook-only.yaml | without_chart_secret
}

# check_file NAME RENDERED: compare a committed manifest with a fresh render.
check_file() {
  if diff -u "$EXAMPLES_DIR/$1" "$2" >&2; then
    echo "examples/kubernetes/$1 is up to date"
  else
    echo "examples/kubernetes/$1 is out of date; run scripts/render_kubernetes_manifest.sh" >&2
    return 1
  fi
}

case "${1:-}" in
  --check)
    stale=0
    check_file k8s-connector-in-cluster-enabled.yaml <(render_kubernetes_in_cluster) || stale=1
    check_file agent-only.yaml <(render_agent_only) || stale=1
    check_file webhook-only.yaml <(render_webhook_only) || stale=1
    exit "$stale"
    ;;
  "")
    mkdir -p "$EXAMPLES_DIR"
    render_kubernetes_in_cluster >"$EXAMPLES_DIR/k8s-connector-in-cluster-enabled.yaml"
    render_agent_only >"$EXAMPLES_DIR/agent-only.yaml"
    render_webhook_only >"$EXAMPLES_DIR/webhook-only.yaml"
    echo "wrote k8s-connector-in-cluster-enabled.yaml, agent-only.yaml and webhook-only.yaml in $EXAMPLES_DIR"
    ;;
  *)
    echo "usage: $0 [--check]" >&2
    exit 2
    ;;
esac
