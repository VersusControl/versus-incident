// Package fakeaws serves deterministic AWS API responses for tests.
//
// It speaks the three wire protocols the product's probe client uses — query
// (form-encoded Action), JSON (X-Amz-Target) and REST (path-routed) — so one
// fixture set can answer STS, EC2 and the rest of the service catalog.
// Standard library only; the product binary never imports it.
package fakeaws

import (
	"fmt"
	"html"
	"io"
	"net/http"
	"net/http/httptest"
	"net/url"
	"os"
	"strconv"
	"strings"
	"sync"
	"time"
)

// Wire protocols the fixture answers.
const (
	protocolQuery = "query"
	protocolJSON  = "json"
	protocolREST  = "rest"
)

const (
	// DefaultScenario is the fixture used when no scenario is requested.
	DefaultScenario = "new-account-connect"
	// ScenarioHeader overrides the scenario for a single request.
	ScenarioHeader = "X-FakeAWS-Scenario"
	// AccountHeader pins the calling account for a single request.
	AccountHeader = "X-FakeAWS-Account"
	// RegionHeader pins the calling region for a single request.
	RegionHeader = "X-FakeAWS-Region"
	// AssumeErrorHeader selects an assume-role failure by identifier.
	AssumeErrorHeader = "X-FakeAWS-Assume-Error"
	// EnvScenario selects the default scenario when New receives "".
	EnvScenario = "FAKEAWS_SCENARIO"
)

// Assume-role failure identifiers accepted by the assume-denied fixture.
const (
	AssumeTrustDenied            = "trust_denied"
	AssumeExternalIDMismatch     = "external_id_mismatch"
	AssumeRoleNotFound           = "role_not_found"
	AssumeSessionDurationInvalid = "session_duration_invalid"
)

const requestID = "00000000-0000-0000-0000-000000000001"

var knownScenarios = map[string]bool{
	"new-account-connect": true,
	"assume-denied":       true,
	"throttled-api":       true,
	"region-disabled":     true,
	"secret-canary":       true,
}

// Account is one fixture account. Services in Denied answer AccessDenied;
// services in Empty answer successfully with zero items.
type Account struct {
	Name            string
	ID              string
	HomeRegion      string
	Denied          map[string]bool
	Empty           map[string]bool
	HealthNotOnPlan bool
}

// TB is the slice of testing.T the fixture needs, so importing the package
// never drags the testing flags into a binary.
type TB interface {
	Helper()
	Fatalf(format string, args ...any)
	Cleanup(func())
}

// Server is an httptest-backed AWS endpoint plus its request counters.
type Server struct {
	http     *httptest.Server
	scenario string

	mu            sync.Mutex
	pathCounts    map[string]int64
	opCounts      map[string]int64
	probeRequests int64
	throttleEvery int

	externalID      string
	disabledRegions map[string]bool
}

// New starts a fake AWS endpoint for the given scenario and stops it when the
// test finishes. An empty scenario falls back to FAKEAWS_SCENARIO, then to
// DefaultScenario. A single request may override it with ScenarioHeader.
func New(t TB, scenario string) *Server {
	t.Helper()
	server, err := NewServer(scenario)
	if err != nil {
		t.Fatalf("fakeaws: %v", err)
	}
	t.Cleanup(server.Close)
	return server
}

// NewServer starts a fixture without a test handle. Callers must Close it.
func NewServer(scenario string) (*Server, error) {
	if scenario == "" {
		scenario = os.Getenv(EnvScenario)
	}
	if scenario == "" {
		scenario = DefaultScenario
	}
	if !knownScenarios[scenario] {
		return nil, fmt.Errorf("unknown scenario %q", scenario)
	}
	server := &Server{
		scenario:        scenario,
		pathCounts:      make(map[string]int64),
		opCounts:        make(map[string]int64),
		disabledRegions: make(map[string]bool),
	}
	switch scenario {
	case "throttled-api":
		server.throttleEvery = 3
	case "region-disabled":
		server.disabledRegions["ap-southeast-1"] = true
	}
	server.http = httptest.NewServer(server)
	return server, nil
}

// Close stops the fixture. New already arranges this at test cleanup.
func (s *Server) Close() {
	if s.http != nil {
		s.http.Close()
	}
}

// URL is the base URL callers point their AWS endpoint override at.
func (s *Server) URL() string { return s.http.URL }

// HTTPClient returns a client that rewrites every request host to this server
// while keeping the path, query and headers intact. Point the probe client's
// HTTP seam at it.
func (s *Server) HTTPClient() *http.Client {
	base, err := url.Parse(s.URL())
	if err != nil {
		// s.URL() is generated by httptest and always parses.
		panic(fmt.Sprintf("fakeaws: bad base URL: %v", err))
	}
	return &http.Client{Transport: &rewriteTransport{base: base, next: http.DefaultTransport}}
}

// Scenario reports the server's default scenario.
func (s *Server) Scenario() string { return s.scenario }

// SetExternalID pins the ExternalId AssumeRole must present. When unset, any
// value shaped like a Versus external id (vrs-ext- plus eight or more
// lowercase letters or digits) is accepted.
func (s *Server) SetExternalID(id string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.externalID = id
}

// ExternalID returns the pinned ExternalId, empty when shape-only validation
// is active.
func (s *Server) ExternalID() string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.externalID
}

// SetThrottle makes every nth non-STS request answer ThrottlingException.
// Zero disables throttling.
func (s *Server) SetThrottle(every int) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.throttleEvery = every
}

// DisabledRegions lists the regions the region-disabled fixture rejects.
func (s *Server) DisabledRegions() []string {
	s.mu.Lock()
	defer s.mu.Unlock()
	regions := make([]string, 0, len(s.disabledRegions))
	for region := range s.disabledRegions {
		regions = append(regions, region)
	}
	sortStrings(regions)
	return regions
}

// Accounts returns the fixture accounts. Every scenario serves all three.
func (s *Server) Accounts() []Account { return fixtureAccounts() }

func fixtureAccounts() []Account {
	return []Account{
		{Name: "Production", ID: "111122223333", HomeRegion: "us-east-1"},
		{Name: "Staging", ID: "444455556666", HomeRegion: "eu-west-1",
			Denied:          map[string]bool{"elasticache": true},
			Empty:           map[string]bool{"config": true, "kinesis": true, "states": true},
			HealthNotOnPlan: true},
		{Name: "Shared services", ID: "777788889999", HomeRegion: "ap-southeast-1"},
	}
}

// PathCount is how many requests arrived at an exact URL path.
func (s *Server) PathCount(path string) int64 {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.pathCounts[path]
}

// OperationCount is how many requests carried one service:Action operation.
func (s *Server) OperationCount(operation string) int64 {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.opCounts[operation]
}

// TotalRequests is every request the fixture has answered.
func (s *Server) TotalRequests() int64 {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.pathCounts["*"]
}

func (s *Server) record(path, operation string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.pathCounts[path]++
	s.pathCounts["*"]++
	s.opCounts[operation]++
}

type rewriteTransport struct {
	base *url.URL
	next http.RoundTripper
}

func (t *rewriteTransport) RoundTrip(request *http.Request) (*http.Response, error) {
	clone := request.Clone(request.Context())
	target := *request.URL
	target.Scheme = t.base.Scheme
	target.Host = t.base.Host
	clone.URL = &target
	clone.Host = t.base.Host
	return t.next.RoundTrip(clone)
}

type awsRequest struct {
	protocol string
	service  string
	action   string
	region   string
	account  Account
	params   url.Values
	path     string
	scenario string
}

func (r awsRequest) operation() string {
	if r.service == "" || r.action == "" {
		return "unknown:Unknown"
	}
	return r.service + ":" + r.action
}

func (s *Server) ServeHTTP(writer http.ResponseWriter, request *http.Request) {
	body, _ := io.ReadAll(io.LimitReader(request.Body, 1<<20))
	parsed := parseRequest(request, body)
	parsed.scenario = s.scenarioFor(request)
	s.record(request.URL.Path, parsed.operation())

	if s.shouldThrottle(parsed) {
		s.writeError(writer, parsed.protocol, http.StatusBadRequest, "ThrottlingException", "Rate exceeded")
		return
	}
	if s.isRegionDisabled(parsed) {
		s.writeError(writer, parsed.protocol, http.StatusBadRequest, "AuthFailure", "AWS was not able to validate the provided access credentials")
		return
	}
	s.serve(writer, parsed)
}

func (s *Server) shouldThrottle(request awsRequest) bool {
	if request.service == "sts" {
		return false
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.throttleEvery <= 0 {
		return false
	}
	s.probeRequests++
	return s.probeRequests%int64(s.throttleEvery) == 0
}

func (s *Server) isRegionDisabled(request awsRequest) bool {
	if request.action == "DescribeRegions" || !regionScoped(request.service) {
		return false
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.disabledRegions[request.region]
}

func regionScoped(service string) bool {
	switch service {
	case "ec2", "lambda", "ecs", "rds":
		return true
	}
	return false
}

func parseRequest(request *http.Request, body []byte) awsRequest {
	parsed := awsRequest{
		path:    request.URL.Path,
		params:  url.Values{},
		region:  request.Header.Get(RegionHeader),
		account: accountForRequest(request),
	}
	parsed.service, parsed.region = signingScope(request, parsed.region)
	if request.Header.Get("smithy-protocol") == "rpc-v2-cbor" {
		parsed.protocol = protocolCBOR
		if queryPathRoute(request.URL.Path, &parsed) {
			// The path carries the operation for CBOR services too.
		}
	}

	if target := request.Header.Get("X-Amz-Target"); target != "" && parsed.protocol != protocolCBOR {
		parsed.protocol = protocolJSON
		if index := strings.LastIndex(target, "."); index >= 0 {
			parsed.action = target[index+1:]
			if parsed.service == "" {
				parsed.service = targetService(target[:index])
			}
		}
	}

	if code := request.Header.Get(AssumeErrorHeader); code != "" {
		parsed.params.Set("__assume_error", code)
	}
	mergeValues(parsed.params, request.URL.Query())
	if len(body) > 0 {
		if form, err := url.ParseQuery(string(body)); err == nil {
			mergeValues(parsed.params, form)
		}
	}
	if action := parsed.params.Get("Action"); action != "" {
		parsed.protocol = protocolQuery
		parsed.action = action
		if parsed.service == "" {
			parsed.service = queryService(action)
		}
	}
	// The AWS query protocol routes the operation through the URL for some
	// services (Health, CloudWatch) instead of an Action parameter.
	if parsed.protocol == "" && queryPathRoute(parsed.path, &parsed) {
		parsed.protocol = protocolQuery
	}

	if parsed.protocol == "" {
		parsed.protocol = protocolREST
		restRoute(request, &parsed)
	}
	if parsed.service == "" && parsed.path != "" {
		parsed.service = restService(parsed.path)
	}
	parsed.service = serviceAlias(parsed.service)
	if parsed.region == "" {
		parsed.region = "us-east-1"
	}
	return parsed
}

func mergeValues(destination, source url.Values) {
	for key, values := range source {
		for _, value := range values {
			destination.Add(key, value)
		}
	}
}

func signingScope(request *http.Request, fallbackRegion string) (string, string) {
	region := fallbackRegion
	authorization := request.Header.Get("Authorization")
	index := strings.Index(authorization, "Credential=")
	if index < 0 {
		return "", region
	}
	credential := authorization[index+len("Credential="):]
	if comma := strings.Index(credential, ","); comma >= 0 {
		credential = credential[:comma]
	}
	parts := strings.Split(strings.TrimSpace(credential), "/")
	if len(parts) < 5 {
		return "", region
	}
	if parts[2] != "" {
		region = parts[2]
	}
	return parts[3], region
}

func targetService(prefix string) string {
	switch {
	case strings.HasPrefix(prefix, "AWSHealth_"):
		return "health"
	case strings.HasPrefix(prefix, "com.amazonaws.cloudtrail."):
		return "cloudtrail"
	case strings.HasPrefix(prefix, "StarlingDoveService"):
		return "config"
	case strings.HasPrefix(prefix, "DynamoDB_"):
		return "dynamodb"
	case strings.HasPrefix(prefix, "AmazonEC2ContainerService"):
		return "ecs"
	case strings.HasPrefix(prefix, "AWSEvents"):
		return "events"
	case strings.HasPrefix(prefix, "Kinesis_"):
		return "kinesis"
	case strings.HasPrefix(prefix, "AmazonStates"), strings.HasPrefix(prefix, "AWSStepFunctions"):
		return "states"
	}
	return ""
}

func queryService(action string) string {
	switch action {
	case "AssumeRole", "GetCallerIdentity":
		return "sts"
	case "DescribeAutoScalingGroups":
		return "autoscaling"
	case "DescribeStacks":
		return "cloudformation"
	case "DescribeAlarms":
		return "cloudwatch"
	case "DescribeInstances", "DescribeRegions":
		return "ec2"
	case "DescribeCacheClusters":
		return "elasticache"
	case "DescribeLoadBalancers":
		return "elasticloadbalancing"
	case "ListRoles":
		return "iam"
	case "DescribeDBInstances":
		return "rds"
	case "ListTopics":
		return "sns"
	case "ListQueues":
		return "sqs"
	}
	return ""
}

func restRoute(request *http.Request, parsed *awsRequest) {
	path := request.URL.Path
	switch {
	case request.Method == http.MethodGet && path == "/":
		parsed.service, parsed.action = "s3", "ListBuckets"
	case strings.HasPrefix(path, "/restapis"):
		parsed.service, parsed.action = "apigateway", "GetRestApis"
	case strings.HasPrefix(path, "/clusters"):
		parsed.service, parsed.action = "eks", "ListClusters"
	case strings.HasPrefix(path, "/2015-03-31/functions"):
		parsed.service, parsed.action = "lambda", "ListFunctions"
	case strings.HasPrefix(path, "/2013-04-01/healthcheck"):
		parsed.service, parsed.action = "route53", "ListHealthChecks"
	case strings.HasPrefix(path, "/2020-05-31/distribution"):
		parsed.service, parsed.action = "cloudfront", "ListDistributions"
	}
}

// queryPathRoute reads the /service/<prefix>/operation/<Action> shape shared by
// the query-protocol services whose SDK no longer sends an Action parameter.
func queryPathRoute(path string, parsed *awsRequest) bool {
	parts := strings.Split(strings.Trim(path, "/"), "/")
	if len(parts) != 4 || parts[0] != "service" || parts[2] != "operation" || parts[3] == "" {
		return false
	}
	parsed.action = parts[3]
	return true
}

// serviceAlias maps an SDK signing name to the catalog service it answers.
func serviceAlias(service string) string {
	if service == "monitoring" {
		return "cloudwatch"
	}
	return service
}

func restService(path string) string {
	switch {
	case strings.HasPrefix(path, "/restapis"):
		return "apigateway"
	case strings.HasPrefix(path, "/clusters"):
		return "eks"
	case strings.HasPrefix(path, "/2015-03-31/functions"):
		return "lambda"
	case strings.HasPrefix(path, "/2013-04-01/healthcheck"):
		return "route53"
	case strings.HasPrefix(path, "/2020-05-31/distribution"):
		return "cloudfront"
	}
	return ""
}

func accountForRequest(request *http.Request) Account {
	if id := request.Header.Get(AccountHeader); id != "" {
		return accountByID(id)
	}
	if token := request.Header.Get("X-Amz-Security-Token"); token != "" {
		if id := twelveDigits(token); id != "" {
			return accountByID(id)
		}
	}
	return accountByID("111122223333")
}

func accountByID(id string) Account {
	for _, account := range fixtureAccounts() {
		if account.ID == id {
			return account
		}
	}
	return Account{Name: "Unknown", ID: id, HomeRegion: "us-east-1"}
}

func twelveDigits(value string) string {
	for index := 0; index+12 <= len(value); index++ {
		candidate := value[index : index+12]
		if digitsOnly(candidate) {
			return candidate
		}
	}
	return ""
}

func digitsOnly(value string) bool {
	for _, character := range value {
		if character < '0' || character > '9' {
			return false
		}
	}
	return len(value) > 0
}

func (s *Server) scenarioFor(request *http.Request) string {
	if scenario := request.Header.Get(ScenarioHeader); knownScenarios[scenario] {
		return scenario
	}
	return s.scenario
}

func (s *Server) writeError(writer http.ResponseWriter, protocol string, status int, code, message string) {
	switch protocol {
	case protocolCBOR:
		writeCBORError(writer, status, code, message)
	case protocolJSON:
		writeBody(writer, "application/x-amz-json-1.1", status,
			`{"__type":`+strconv.Quote(code)+`,"message":`+strconv.Quote(message)+`}`)
	case protocolREST:
		writeBody(writer, "application/xml", status, xmlErrorBody(code, message))
	default:
		writeBody(writer, "text/xml", status, xmlErrorBody(code, message))
	}
}

func xmlErrorBody(code, message string) string {
	return `<ErrorResponse><Error><Type>Sender</Type><Code>` + xmlEscape(code) +
		`</Code><Message>` + xmlEscape(message) + `</Message></Error>` +
		`<RequestId>` + requestID + `</RequestId></ErrorResponse>`
}

func writeBody(writer http.ResponseWriter, contentType string, status int, body string) {
	writer.Header().Set("Content-Type", contentType)
	writer.WriteHeader(status)
	_, _ = io.WriteString(writer, body)
}

func writeJSONBody(writer http.ResponseWriter, body string) {
	writeBody(writer, "application/x-amz-json-1.1", http.StatusOK, body)
}

func writeRESTJSONBody(writer http.ResponseWriter, body string) {
	writeBody(writer, "application/json", http.StatusOK, body)
}

func writeXMLBody(writer http.ResponseWriter, body string) {
	writeBody(writer, "text/xml", http.StatusOK, body)
}

func writeRESTXMLBody(writer http.ResponseWriter, body string) {
	writeBody(writer, "application/xml", http.StatusOK, body)
}

// queryResult wraps a query-protocol result body in its response envelope.
func queryResult(action, inner string) string {
	return "<" + action + "Response xmlns=\"https://fakeaws.versus\">" +
		"<" + action + "Result>" + inner + "</" + action + "Result>" +
		"<ResponseMetadata><RequestId>" + requestID + "</RequestId></ResponseMetadata>" +
		"</" + action + "Response>"
}

func xmlEscape(value string) string { return html.EscapeString(value) }

func quote(value string) string { return strconv.Quote(value) }

func xmlText(element, value string) string {
	return "<" + element + ">" + xmlEscape(value) + "</" + element + ">"
}

func nowISO() string { return time.Now().UTC().Format(time.RFC3339) }

func sortStrings(values []string) {
	for index := 1; index < len(values); index++ {
		for back := index; back > 0 && values[back] < values[back-1]; back-- {
			values[back], values[back-1] = values[back-1], values[back]
		}
	}
}
